// Bundles the plugin's own filter code for the community pages, so every simulated image on
// the cover and slides is real plugin output (not a mock-up).
//
//   node documentation/community/make-lib.mjs   (render.mjs runs it automatically)
//
// Transpiles src/utils/*.ts with the project's TypeScript into one classic script,
// src/lib/filters.js, with a tiny module registry, and exposes the parts the pages need as
// window.VAS (renderStack, quickSimulationConfig, DEFAULT_PRESETS, FILTER_METADATA, ...).

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..", "..");
const ts = createRequire(path.join(root, "package.json"))("typescript");

// Dependency order doesn't matter (modules load on first require), but keep it readable
const MODULES = [
  "vision-simulator.types",
  "machado-matrices",
  "vision-simulator.constants",
  "image-utils",
  "simulation-render",
  "preset-validation",
];

const parts = [
  "// Generated by make-lib.mjs from src/utils/*.ts. Don't edit; re-run render.mjs.",
  "(function () {",
  "  const defs = {};",
  "  const cache = {};",
  "  function req(name) {",
  "    const key = name.replace(/^\\.\\//, \"\");",
  "    if (cache[key]) return cache[key].exports;",
  "    if (!defs[key]) throw new Error(\"filters.js: unknown module \" + name);",
  "    const module = { exports: {} };",
  "    cache[key] = module;",
  "    defs[key](module, module.exports, req);",
  "    return module.exports;",
  "  }",
];

for (const name of MODULES) {
  const source = fs.readFileSync(path.join(root, "src", "utils", name + ".ts"), "utf8");
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2017 },
  }).outputText;
  parts.push(`  defs[${JSON.stringify(name)}] = function (module, exports, require) {`, js, "  };");
}

parts.push(
  "  window.VAS = Object.assign(",
  "    {},",
  ...MODULES.map((name) => `    req(${JSON.stringify(name)}),`),
  "  );",
  "})();",
  ""
);

const out = path.join(here, "src", "lib", "filters.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, parts.join("\n"));
console.log("✓ src/lib/filters.js (" + MODULES.length + " modules from src/utils)");
